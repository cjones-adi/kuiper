#!/bin/bash
# gen-device-dropins.sh — deterministically generate the per-device user-space
# drop-in package that exposes a Linux hwmon device in Redfish + the OpenBMC web
# UI on a Kuiper image that already has the BMC framework (Phase 1 of the
# kuiper-bmc-integrate flow). NO hardware access and NO image rebuild required:
# it emits text files + a deploy.sh you run on the target and a validate.sh you
# run from any host that can reach the Pi over HTTPS.
#
# It reproduces, parameterized, the exact file shapes validated on the Pi for the
# ADM1600 (see ../assets/*). Adding a device is then: run this -> copy out/ to the
# Pi -> ./deploy.sh -> ./validate.sh.
#
# Usage:
#   gen-device-dropins.sh --name <hwmon_name> \
#       --channel <chan>=<label> [--channel ...] \
#       [--addr 0xNN] [--overlay <name>] [--chassis <name>] \
#       [--display-name <name>] [--out <dir>]
#
#   --name          REQUIRED. The driver's hwmon `name` (cat /sys/class/hwmon/*/name).
#                   Also the default chassis id and the sensor-label prefix.
#   --channel       REQUIRED, repeatable. A standard hwmon channel = short label,
#                   e.g. in1=Vin curr1=Iin power1=Pin temp1=Temp fan1=Fan.
#                   Channel prefix picks the D-Bus sensor type:
#                     in->voltage curr->current power->power temp->temperature fan->fan_tach
#                   The published label becomes <name>_<label>.
#   --addr          Optional I2C address (for the config.txt comment), e.g. 0x48.
#   --overlay       Optional devicetree overlay name (default: <name>).
#   --chassis       Optional Redfish chassis id (default: <name>).
#   --display-name  Optional chassis display name (default: <name>).
#   --out           Optional output dir (default: ./out/<name>).
#
# Example (the ADM1600):
#   gen-device-dropins.sh --name adm1600 --addr 0x48 \
#       --channel in1=Vin --channel curr1=Iin --channel power1=Pin
#
# If you don't yet know the name/channels, run this once on the target and paste
# the result into --channel flags:
#   for d in /sys/class/hwmon/hwmon*; do echo "name=$(cat $d/name)"; ls $d | grep -E '_input$'; done
set -euo pipefail

die() { echo "ERROR: $*" >&2; exit 1; }

NAME="" ADDR="" OVERLAY="" CHASSIS="" DISPLAY="" OUT=""
CH_KEYS=() CH_LABELS=()

while [ $# -gt 0 ]; do
	case "$1" in
		--name)         NAME="${2:-}"; shift 2 ;;
		--addr)         ADDR="${2:-}"; shift 2 ;;
		--overlay)      OVERLAY="${2:-}"; shift 2 ;;
		--chassis)      CHASSIS="${2:-}"; shift 2 ;;
		--display-name) DISPLAY="${2:-}"; shift 2 ;;
		--out)          OUT="${2:-}"; shift 2 ;;
		--channel)
			spec="${2:-}"; shift 2
			[ -n "$spec" ] || die "--channel needs <chan>=<label>"
			case "$spec" in *=*) : ;; *) die "--channel must be <chan>=<label>, got '$spec'";; esac
			CH_KEYS+=("${spec%%=*}")
			CH_LABELS+=("${spec#*=}")
			;;
		-h|--help) grep '^#' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
		*) die "unknown arg: $1 (try --help)" ;;
	esac
done

[ -n "$NAME" ] || die "--name is required"
[ "${#CH_KEYS[@]}" -gt 0 ] || die "at least one --channel is required"
OVERLAY="${OVERLAY:-$NAME}"
CHASSIS="${CHASSIS:-$NAME}"
DISPLAY="${DISPLAY:-$NAME}"
OUT="${OUT:-./out/$NAME}"

# hwmon channel prefix -> D-Bus sensor-type subtree
chan_type() {
	case "${1%%[0-9]*}" in
		in)    echo voltage ;;
		curr)  echo current ;;
		power) echo power ;;
		temp)  echo temperature ;;
		fan)   echo fan_tach ;;
		*) die "unsupported channel '$1' (prefix must be in/curr/power/temp/fan)" ;;
	esac
}

mkdir -p "$OUT"

# ---- 1. phosphor-hwmon config: <name>-hwmon.conf --------------------------------
{
	echo "# phosphor-hwmon configuration for $NAME (generated by gen-device-dropins.sh)."
	echo "# Installed at first boot to /etc/default/obmc/hwmon/<OF-instance>.conf by"
	echo "# obmc-hwmon-$NAME-setup.sh (the filename mirrors the device-tree %I path)."
	echo "# Only STANDARD hwmon channels are phosphor-hwmon-native; vendor attributes"
	echo "# with non-standard encodings need a separate custom D-Bus service."
	echo
	echo "# D-Bus busname suffix: xyz.openbmc_project.Hwmon-$NAME.Hwmon1"
	echo "HW_SENSOR_ID=$NAME"
	echo
	echo "# Sensor labels -> D-Bus /xyz/openbmc_project/sensors/<type>/<label>"
	for i in "${!CH_KEYS[@]}"; do
		echo "LABEL_${CH_KEYS[$i]}=${NAME}_${CH_LABELS[$i]}"
	done
} > "$OUT/$NAME-hwmon.conf"

# ---- 2. bmc-assoc drop-in: <name>.conf -----------------------------------------
{
	echo "# bmc-assoc config for $NAME (generated). Installed to /etc/bmc-assoc/$NAME.conf."
	echo "# Publishes chassis '$CHASSIS' + an all_sensors association so bmcweb serves"
	echo "# /redfish/v1/Chassis/$CHASSIS/Sensors. SENSOR subpaths MUST equal the"
	echo "# <type>/<label> published by $NAME-hwmon.conf. Add/adjust then:"
	echo "#   systemctl restart bmc-assoc   (no recompile, no image rebuild)"
	echo
	echo "CHASSIS=$CHASSIS"
	echo "NAME=$DISPLAY"
	for i in "${!CH_KEYS[@]}"; do
		echo "SENSOR=$(chan_type "${CH_KEYS[$i]}")/${NAME}_${CH_LABELS[$i]}"
	done
} > "$OUT/$NAME.conf"

# ---- 3. first-boot instantiator: obmc-hwmon-<name>-setup.sh ---------------------
cat > "$OUT/obmc-hwmon-$NAME-setup.sh" <<EOF
#!/bin/bash
# Discover the $NAME hwmon instance at runtime, install its phosphor-hwmon config
# at the device-tree-path-derived location the systemd template unit expects (%I),
# then start the poller. Idempotent. (generated by gen-device-dropins.sh)
set -euo pipefail

TEMPLATE=/usr/share/$NAME/$NAME-hwmon.conf
CONFROOT=/etc/default/obmc/hwmon

hwmon=""
for d in /sys/class/hwmon/hwmon*; do
	[ -r "\$d/name" ] || continue
	if [ "\$(cat "\$d/name")" = "$NAME" ]; then hwmon="\$d"; break; fi
done
[ -n "\$hwmon" ] || { echo "ERROR: $NAME hwmon not found (driver bound? overlay loaded?)" >&2; exit 1; }
echo "Found $NAME hwmon: \$hwmon"

ofnode="\$hwmon/device/of_node"
if [ -e "\$ofnode" ]; then
	full="\$(readlink -f "\$ofnode")"
	ofpath="\${full#/sys/firmware/devicetree/base}"
else
	dp="\$(readlink -f "\$hwmon/device")"; ofpath="\${dp#/sys}"
fi
echo "Device OF/dev path: \$ofpath"

colon="\${ofpath//:/--}"
esc="\$(systemd-escape "\$colon")"
conf="\${CONFROOT}\${colon}.conf"
install -d "\$(dirname "\$conf")"
install -m644 "\$TEMPLATE" "\$conf"
echo "Installed config: \$conf"

unit="xyz.openbmc_project.Hwmon@\${esc}.service"
systemctl start "\$unit"
echo "Started \$unit"
EOF
chmod +x "$OUT/obmc-hwmon-$NAME-setup.sh"

# ---- 4. oneshot service: obmc-hwmon-<name>.service -----------------------------
cat > "$OUT/obmc-hwmon-$NAME.service" <<EOF
[Unit]
Description=Configure and start phosphor-hwmon for the $NAME
After=xyz.openbmc_project.ObjectMapper.service
Wants=xyz.openbmc_project.ObjectMapper.service
ConditionPathExists=/sys/class/hwmon

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStartPre=/bin/sh -c 'for i in \$(seq 1 30); do grep -qx $NAME /sys/class/hwmon/hwmon*/name 2>/dev/null && exit 0; sleep 1; done; exit 0'
ExecStart=/usr/bin/obmc-hwmon-$NAME-setup.sh

[Install]
WantedBy=multi-user.target
EOF

# ---- 5. boot bits: config.txt snippet + i2c modules-load -----------------------
{
	echo ""
	echo "# --- $NAME BMC kernel + sensor overlay ${ADDR:+(I2C $ADDR)} ---"
	echo "# [all] resets any preceding conditional filter (the base Kuiper config.txt"
	echo "# ends in a [cm5] section; without [all] these are silently skipped on a Pi4)."
	echo "[all]"
	echo "kernel=kernel8.img"
	echo "dtparam=i2c_arm=on"
	echo "dtoverlay=$OVERLAY"
} > "$OUT/config.txt.snippet"

printf 'i2c-bcm2835\ni2c-dev\n' > "$OUT/$NAME-i2c.conf"

# ---- 6. deploy.sh (run on the target as root; user-space drop-ins only) --------
cat > "$OUT/deploy.sh" <<EOF
#!/bin/bash
# Install the $NAME user-space drop-ins on a Kuiper image that ALREADY has the BMC
# framework. Run as root on the target (or via your own ssh). Reversible; touches
# NO boot/kernel state. Prerequisite (done separately, GATED): kernel image + the
# $OVERLAY overlay + config.txt lines applied and the Pi rebooted so '$NAME'
# appears in /sys/class/hwmon/*/name.
set -euo pipefail
here="\$(cd "\$(dirname "\$0")" && pwd)"

if ! grep -qx $NAME /sys/class/hwmon/hwmon*/name 2>/dev/null; then
	echo "WARN: '$NAME' not in /sys/class/hwmon yet — do the kernel/overlay/config.txt step + reboot first." >&2
fi

install -Dm644 "\$here/$NAME-hwmon.conf"          /usr/share/$NAME/$NAME-hwmon.conf
install -Dm755 "\$here/obmc-hwmon-$NAME-setup.sh" /usr/bin/obmc-hwmon-$NAME-setup.sh
install -Dm644 "\$here/obmc-hwmon-$NAME.service"  /usr/lib/systemd/system/obmc-hwmon-$NAME.service
install -Dm644 "\$here/$NAME.conf"                /etc/bmc-assoc/$NAME.conf
install -Dm644 "\$here/$NAME-i2c.conf"            /etc/modules-load.d/$NAME-i2c.conf

systemctl daemon-reload
systemctl enable --now obmc-hwmon-$NAME.service
systemctl restart bmc-assoc.service
echo "Deployed $NAME. Validate with: ./validate.sh <pi-host-or-ip>"
EOF
chmod +x "$OUT/deploy.sh"

# ---- 7. validate.sh (run from any host that can reach the Pi over HTTPS) --------
SENSOR_COUNT="${#CH_KEYS[@]}"
cat > "$OUT/validate.sh" <<EOF
#!/bin/bash
# Validate $NAME over Redfish. Runs from any host that can curl the Pi (no ssh).
# Usage: ./validate.sh [pi-host-or-ip]   (default localhost, i.e. run on the Pi)
set -uo pipefail
HOST="\${1:-localhost}"
base="https://\$HOST/redfish/v1"
echo "== Chassis list =="
curl -sk "\$base/Chassis" | grep -o '"@odata.id":"[^"]*"' || true
echo
echo "== $CHASSIS sensors (expect $SENSOR_COUNT) =="
out="\$(curl -sk "\$base/Chassis/$CHASSIS/Sensors")"
echo "\$out" | grep -o '"@odata.id":"[^"]*"' || true
n="\$(echo "\$out" | grep -o '/Sensors/[^"]*' | grep -v '/Sensors"' | sort -u | wc -l)"
echo
if echo "\$out" | grep -q '"Members@odata.count": *0\|"error"'; then
	cat <<'DIAG'
DIAGNOSIS: chassis present but Sensors empty. Walk the chain (see the
kuiper-bmc-hwmon skill troubleshooting table), most-likely first:
  1. bmc-assoc conf paths != phosphor-hwmon LABEL_* -> fix $NAME.conf SENSOR= lines.
  2. phosphor-hwmon not publishing -> is obmc-hwmon-$NAME.service active? is
     '$NAME' in /sys/class/hwmon/*/name? (kernel/overlay step done + rebooted?)
  3. mapper didn't index -> Debian D-Bus policy gotcha; the OPEN policy
     (blanket <allow send_type="method_call"/>) must be installed (framework image).
  4. association still pending -> normal until the sensors exist; it self-heals.
On-target deep check:
  busctl call xyz.openbmc_project.ObjectMapper /xyz/openbmc_project/object_mapper \\
    xyz.openbmc_project.ObjectMapper GetSubTreePaths sias \\
    /xyz/openbmc_project/sensors 0 1 xyz.openbmc_project.Sensor.Value
DIAG
else
	echo "OK: $CHASSIS exposes sensors."
fi
EOF
chmod +x "$OUT/validate.sh"

# ---- 8. README for the package -------------------------------------------------
cat > "$OUT/README.txt" <<EOF
$NAME BMC drop-in package (generated by gen-device-dropins.sh)
=============================================================
Target: a Kuiper (Debian arm64, RPi4) image that ALREADY has the OpenBMC BMC
framework (bmcweb + phosphor-objmgr + phosphor-hwmon + generic bmc-assoc + open
D-Bus policy + usermgr login). This package only adds the per-device glue.

Files:
  $NAME-hwmon.conf           phosphor-hwmon labels (in/curr/power/... -> D-Bus)
  obmc-hwmon-$NAME-setup.sh  first-boot OF-path instantiator
  obmc-hwmon-$NAME.service   oneshot that runs the instantiator
  $NAME.conf                 bmc-assoc drop-in -> chassis + all_sensors association
  $NAME-i2c.conf             /etc/modules-load.d (i2c-dev, i2c-bcm2835)
  config.txt.snippet         boot lines (kernel/dtparam/dtoverlay under [all])
  deploy.sh                  install the user-space drop-ins on the target (as root)
  validate.sh                Redfish validation from any host (curl only, no ssh)

Steps:
  1. KERNEL/BOOT (developer artifacts, GATED): install the kernel image + the
     $OVERLAY overlay, append config.txt.snippet to /boot/config.txt, then reboot.
     Confirm: '$NAME' appears in /sys/class/hwmon/*/name.
  2. DEPLOY (user space): copy this folder to the Pi and run  sudo ./deploy.sh
  3. VALIDATE:  ./validate.sh <pi-host-or-ip>   (or run on the Pi with no arg)
  4. Web UI:    https://<pi>   login analog / analog
EOF

echo "Generated $NAME drop-in package in: $OUT"
ls -1 "$OUT"
